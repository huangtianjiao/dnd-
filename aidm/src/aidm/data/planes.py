from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
from typing import Optional


# ──────────────────────────────────────────────────────────────────────────
# 枚举
# ──────────────────────────────────────────────────────────────────────────

class PlaneType(Enum):
    """位面类型分类。

    出处: 城主指南2024/6.宇宙学/诸位面.htm
      - 物质界域 Material Realms: 物质位面 + 妖精荒野 + 堕影冥界
      - 中转位面 Transitive Planes: 以太位面 + 星光位面
      - 内层位面 Inner Planes: 四元素位面 + 次生元素位面
      - 外层位面 Outer Planes: 十七个对应阵营的位面
      - 正负位面 Positive/Negative Planes: 生死原初力量
      - 半位面 Demiplanes: 由法术或自然产生的超次元空间
    """
    MATERIAL = "物质界域"
    ETHEREAL = "中转位面-以太"
    ASTRAL = "中转位面-星光"
    INNER = "内层位面"
    OUTER = "外层位面"
    POSITIVE_NEGATIVE = "正负位面"
    DEMIPLANE = "半位面"


# ──────────────────────────────────────────────────────────────────────────
# 数据类
# ──────────────────────────────────────────────────────────────────────────

@dataclass
class Plane:
    """单个位面的完整数据。

    字段说明:
      name:        中文名
      name_en:     英文名
      plane_type:  位面类型 (PlaneType)
      alignment:   阵营归属（外层位面用），如 "守序邪恶"
      description: 位面描述（从 HTML 原文提炼）
      inhabitants: 典型居民列表
      hazards:     位面危害列表（每项为 Hazard 描述字符串）
      portals:     该位面已知的传送门/通道列表
      layers:      位层列表（多位层位面用），每项 {"name": ..., "desc": ...}
      source:      HTML 原文路径，用于规则追溯
    """
    name: str
    name_en: str
    plane_type: PlaneType
    alignment: str = ""
    description: str = ""
    inhabitants: list[str] = field(default_factory=list)
    hazards: list[str] = field(default_factory=list)
    portals: list[str] = field(default_factory=list)
    layers: list[dict] = field(default_factory=list)
    source: str = ""

    def to_dict(self) -> dict:
        """序列化为字典（供 API 返回）。"""
        return {
            "name": self.name,
            "name_en": self.name_en,
            "plane_type": self.plane_type.value,
            "alignment": self.alignment,
            "description": self.description,
            "inhabitants": self.inhabitants,
            "hazards": self.hazards,
            "portals": self.portals,
            "layers": self.layers,
            "source": self.source,
        }


# ──────────────────────────────────────────────────────────────────────────
# 位面数据库
# 数据来源: 城主指南2024/6.宇宙学/多元宇宙之旅/*.htm
# ──────────────────────────────────────────────────────────────────────────

PLANES: dict[str, Plane] = {}


def _register(plane: Plane) -> None:
    """将位面注册到 PLANES 字典（按中文名和英文名均可索引）。"""
    PLANES[plane.name] = plane
    if plane.name_en and plane.name_en != plane.name:
        PLANES[plane.name_en] = plane


