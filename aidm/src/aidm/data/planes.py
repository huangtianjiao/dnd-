def get_plane(name: str) -> Optional[Plane]:
    """按名称查询位面（支持中文名或英文名）。

    Args:
        name: 位面名称（中文或英文）

    Returns:
        匹配的 Plane 对象，未找到返回 None

    出处: 本函数为数据访问层，数据来源于 DMG 第六章各位面 HTML 文件
    """
    # 精确匹配
    if name in PLANES:
        return PLANES[name]
    # 大小写不敏感匹配英文名
    lower_name = name.lower()
    for key, plane in PLANES.items():
        if key.lower() == lower_name or plane.name_en.lower() == lower_name:
            return plane
    return None


def list_planes(plane_type: Optional[PlaneType] = None) -> list[Plane]:
    """列出所有位面，可按类型筛选。

    注意: PLANES 字典同时以中文名和英文名为键，为避免重复，
          此函数仅返回每个位面一次（以中文名为准）。

    Args:
        plane_type: 可选的位面类型筛选

    Returns:
        位面列表，按注册顺序排列

    出处: 本函数为数据访问层，数据来源于 DMG 第六章各位面 HTML 文件
    """
    seen = set()
    result = []
    for plane in PLANES.values():
        if plane.name in seen:
            continue
        if plane_type is not None and plane.plane_type != plane_type:
            continue
        seen.add(plane.name)
        result.append(plane)
    return result


def get_portals(plane_name: str) -> list[str]:
    """获取指定位面的传送门/通道列表。

    Args:
        plane_name: 位面名称（中文或英文）

    Returns:
        传送门描述列表，未找到位面则返回空列表

    出处: 传送门数据来源于 城主指南2024/6.宇宙学/位面旅行.htm 及各位面 HTML 文件
    """
    plane = get_plane(plane_name)
    if plane is None:
        return []
    return plane.portals


def search_planes(keyword: str) -> list[Plane]:
    """按关键词搜索位面（匹配名称、描述、居民、危害）。

    Args:
        keyword: 搜索关键词

    Returns:
        匹配的位面列表

    出处: 本函数为数据访问层，数据来源于 DMG 第六章各位面 HTML 文件
    """
    keyword_lower = keyword.lower()
    seen = set()
    result = []
    for plane in PLANES.values():
        if plane.name in seen:
            continue
        searchable = (
            plane.name, plane.name_en, plane.description,
            plane.alignment, *plane.inhabitants,
            *plane.hazards, *plane.portals,
        )
        if any(keyword_lower in str(s).lower() for s in searchable):
            seen.add(plane.name)
            result.append(plane)
    return result


def get_plane_count() -> int:
    """返回已注册的位面总数（去重）。"""
    seen = set()
    for plane in PLANES.values():
        seen.add(plane.name)
    return len(seen)


