def get_features_for_level(class_name: str, level: int) -> list[str]:
    """取某职业在某等级获得的特性列表。

    规则: 等级提升.htm Step3「记录新职业特性」
    出处: topics/玩家手册2024/角色职业/<职业>/<职业>.htm
    """
    features = CLASS_FEATURES.get(class_name, {})
    return list(features.get(level, []))


def get_rage_uses(level: int) -> int:
    """野蛮人狂暴次数。出处: 野蛮人.htm"""
    return RAGE_USES_BY_LEVEL.get(level, 6)


def get_rage_damage(level: int) -> int:
    """野蛮人狂暴伤害加值。出处: 野蛮人.htm"""
    return RAGE_DAMAGE_BY_LEVEL.get(level, 4)


def get_action_surge_uses(level: int) -> int:
    """战士行动涌动次数。出处: 战士.htm"""
    return FIGHTER_ACTION_SURGE_BY_LEVEL.get(level, 2)


def get_extra_attacks(class_name: str, level: int) -> int:
    """某职业在某等级的额外攻击次数。

    规则: 兼职.htm — 额外攻击不叠加（多源只取最高）
    出处: topics/玩家手册2024/创建角色/兼职.htm
    """
    if class_name == "战士":
        return FIGHTER_EXTRA_ATTACK_BY_LEVEL.get(level, 3)
    # 野蛮人/圣武士/游侠/武僧：5级1次额外攻击
    if class_name in ("野蛮人", "圣武士", "游侠", "武僧", "吟游诗人"):
        return 1 if level >= 5 else 0
    return 0


def get_class_features_dict(class_name: str, level: int) -> dict:
    """取某职业1~level级的所有特性（汇总字典）。

    返回: {level: [feature_names], ...} 从1级到当前等级
    """
    result = {}
    features = CLASS_FEATURES.get(class_name, {})
    for lv in range(1, level + 1):
        if lv in features:
            result[lv] = list(features[lv])
    return result


def get_class(name: str) -> dict:
    """取职业条目。"""
    if name not in CLASSES:
        raise KeyError(f"未知职业 {name!r}，可选: {list(CLASSES)}")
    return CLASSES[name]


def class_names() -> list[str]:
    """返回全部职业名（按定义顺序）。"""
    return list(CLASSES)


